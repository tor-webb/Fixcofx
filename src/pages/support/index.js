import { DEMO_CONFIG } from '../../config/demo.config.js';
import { SITE } from '../../config/site.config.js';
import { pageHead, siteFooter, esc } from '../../components/ui.js';

export const title = 'Support';

const FAQ = [
  { q: 'What is demo mode?', a: 'Demo mode means everything you see is simulated: prices, charts, news, balances, orders and support replies. It exists so the full workflow can be tested without real money or real brokers.' },
  { q: 'Are the prices real?', a: 'No. Prices are generated by a simulation engine and are labelled as simulated wherever they appear. They are not live market prices and must not be used for real trading decisions.' },
  { q: 'Can I deposit or withdraw money?', a: 'No. Real deposits and withdrawals are not available. Any balance shown in a later build will be a fictional demo balance.' },
  { q: 'Can I trade real assets?', a: 'No. Demo orders go to a simulated engine that is isolated from any broker or exchange. Real execution needs a broker agreement and regulatory approval that are not in place.' },
  { q: 'How do I create an account or log in?', a: 'Sign up and sign in from the top-right of the page. Your account is created on this project\'s Supabase instance and includes a fictional USD 10,000 demo balance.' },
  { q: 'Is there an AI assistant?', a: 'Not yet. A scripted demo assistant is planned, and it will be labelled "' + DEMO_CONFIG.supportLabel + '". A real AI service will only be offered once one is connected.' },
  { q: 'Is the news real?', a: 'No. The news page will show fictional samples labelled "' + DEMO_CONFIG.newsLabel + '". It is for testing the interface, not for information about real markets.' },
  { q: 'Does this work with MetaTrader 4 or 5?', a: 'Not yet. MetaTrader connectivity needs an authorised integration from a broker or provider. No broker is connected, and no account will be shown as connected until it is verified.' },
  { q: 'What happens if I go offline?', a: 'A red banner appears and prices stop updating. Orders cannot be submitted while offline, and the app will not show an order as sent or filled without a confirmed response.' },
  { q: 'Is this financial advice?', a: 'No. Fiscofx provides platform support and general education only. It is not a licensed financial adviser. Trading can result in the loss of money.' },
];

let root = null;
let onInput = null;

function contactRow(label, value, href) {
  return value
    ? `<li><span class="muted">${label}</span> <a href="${href}">${esc(value)}</a></li>`
    : `<li><span class="muted">${label}</span> <span class="chip">Not configured yet</span></li>`;
}

export function mount(el) {
  root = el;
  const c = SITE.contacts;
  el.innerHTML = `
    <div class="page">
      ${pageHead('Support', 'How can we help?', 'Find answers, see how to reach a person, and check when the guided assistant arrives.')}

      <section class="section" aria-labelledby="entry-title">
        <h2 id="entry-title" class="sr-only">Ways to get help</h2>
        <ul class="card-grid" role="list">
          <li class="card">
            <div class="card-top"><h3>Guided assistant</h3><span class="chip chip-warn">${esc(DEMO_CONFIG.supportLabel)}</span></div>
            <p>A scripted help assistant is planned for a later phase. It will answer from a fixed FAQ, and will not claim to be an AI service.</p>
            <button class="btn" type="button" disabled>Not available yet</button>
          </li>
          <li class="card">
            <h3>Contact a person</h3>
            <ul class="plain-list">
              ${contactRow('Email', c.email, `mailto:${c.email}`)}
              ${contactRow('Phone', c.phone, `tel:${c.phone}`)}
              ${contactRow('Hours', c.hours, '#/support')}
            </ul>
            <p class="small muted">Contact details are set in <span class="mono">src/config/site.config.js</span> once real channels exist.</p>
          </li>
          <li class="card">
            <h3>Read the disclosures</h3>
            <p>What is simulated, what is not connected, and the risks of trading.</p>
            <a class="btn btn-link" href="#/disclosures">Demo disclosures</a>
          </li>
        </ul>
      </section>

      <section class="section" aria-labelledby="faq-title">
        <h2 id="faq-title">Frequently asked questions</h2>
        <div class="toolbar" role="search">
          <label class="sr-only" for="faq-q">Search questions</label>
          <input id="faq-q" class="input" type="search" placeholder="Search questions" autocomplete="off" maxlength="60">
        </div>
        <p id="faq-status" class="small muted" role="status" aria-live="polite"></p>
        <div class="faq">
          ${FAQ.map((f) => `
            <details class="faq-item" data-text="${esc((f.q + ' ' + f.a).toLowerCase())}">
              <summary>${esc(f.q)}</summary>
              <p>${esc(f.a)}</p>
            </details>`).join('')}
        </div>
      </section>

      <section class="section panel" aria-labelledby="ts-title">
        <h2 id="ts-title">Quick troubleshooting</h2>
        <ul class="check-list">
          <li><strong>Red offline banner:</strong> your device has lost its connection. Reconnect and the banner clears itself.</li>
          <li><strong>Page didn't load:</strong> refresh. If it persists, clear the site's cached data in your browser.</li>
          <li><strong>A page says it arrives in a later phase:</strong> that section is not built yet. See the <a href="#/product">status list</a>.</li>
        </ul>
      </section>

      ${siteFooter()}
    </div>`;

  const q = el.querySelector('#faq-q');
  const status = el.querySelector('#faq-status');
  onInput = () => {
    const term = q.value.trim().toLowerCase();
    let shown = 0;
    el.querySelectorAll('.faq-item').forEach((d) => {
      const ok = !term || d.dataset.text.includes(term);
      d.hidden = !ok;
      if (ok) shown++;
    });
    status.textContent = term ? (shown ? `${shown} matching ${shown === 1 ? 'question' : 'questions'}.` : 'No matching questions. Try different words, or contact a person.') : '';
  };
  q.addEventListener('input', onInput);
}

export function unmount() {
  root = onInput = null;
}
