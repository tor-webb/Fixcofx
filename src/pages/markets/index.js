import { INSTRUMENTS, ASSET_CLASS_META, searchInstruments } from '../../data/instruments.js';
import { startPrices, stopPrices, subscribePrices, latestSnapshot } from '../../engine/prices.js';
import { fmtPrice, fmtPct, dirClass } from '../../lib/format.js';
import { loadWatchlist, toggleWatched } from '../../services/watchlist.js';
import { pageHead, siteFooter, esc } from '../../components/ui.js';

export const title = 'Markets';

let root = null;
let unsub = null;
let onClick = null;
let onInput = null;
let state = { term: '', cat: 'all', watchOnly: false };

export function mount(el) {
  root = el;
  startPrices();
  state = { term: '', cat: 'all', watchOnly: false };

  el.innerHTML = `
    <div class="page">
      ${pageHead('Markets', 'Market catalogue', `${INSTRUMENTS.length} simulated instruments across ${Object.keys(ASSET_CLASS_META).length} categories.`)}
      <div class="notice" role="note">
        <strong>Simulated prices.</strong> Every price on this page is generated by a seeded simulation engine and is labelled <span class="chip chip-warn">SIMULATED</span>. Prices are not live and must not be used for real trading.
      </div>

      <div class="toolbar" role="search">
        <label class="sr-only" for="mkt-q">Search instruments</label>
        <input id="mkt-q" class="input" type="search" placeholder="Search symbol or name, e.g. EUR, BTC, Apple" autocomplete="off" maxlength="40">
        <div class="seg" role="group" aria-label="Filter by category">
          <button type="button" class="seg-btn" data-cat="all" aria-pressed="true">All</button>
          ${Object.entries(ASSET_CLASS_META).map(([id, m]) =>
            `<button type="button" class="seg-btn" data-cat="${esc(id)}" aria-pressed="false">${esc(m.name)}</button>`
          ).join('')}
          <button type="button" class="seg-btn" data-watch="1" aria-pressed="false">Watchlist</button>
        </div>
      </div>
      <p id="mkt-status" class="small muted" role="status" aria-live="polite"></p>

      <div class="table-wrap">
        <table class="table" aria-label="Simulated instruments">
          <thead>
            <tr>
              <th scope="col">Symbol</th>
              <th scope="col">Name</th>
              <th scope="col" class="num">Price</th>
              <th scope="col" class="num">Change</th>
              <th scope="col" class="num">Bid / Ask</th>
              <th scope="col"><span class="sr-only">Watch</span></th>
            </tr>
          </thead>
          <tbody id="mkt-body"></tbody>
        </table>
      </div>

      ${siteFooter()}
    </div>`;

  const q = el.querySelector('#mkt-q');
  const status = el.querySelector('#mkt-status');
  const body = el.querySelector('#mkt-body');

  const rerender = (snapshot) => {
    const priceMap = new Map(snapshot.map((p) => [p.id, p]));
    const list = searchInstruments(state.term, state.cat);
    const watched = new Set(loadWatchlist());
    const filtered = state.watchOnly ? list.filter((i) => watched.has(i.id)) : list;
    body.replaceChildren();
    if (filtered.length === 0) {
      body.innerHTML = `<tr><td colspan="6" class="muted">No matching instruments.${state.watchOnly ? ' Add some from the Watch column.' : ''}</td></tr>`;
    } else {
      body.innerHTML = filtered.map((ins) => {
        const p = priceMap.get(ins.id) || {};
        const w = watched.has(ins.id);
        return `
          <tr data-id="${esc(ins.id)}">
            <td><a class="mono" href="#/instrument/${encodeURIComponent(ins.id)}">${esc(ins.symbol)}</a>
                <span class="chip chip-warn small" title="Simulated">SIM</span></td>
            <td>${esc(ins.name)}</td>
            <td class="num mono">${fmtPrice(p.price, ins.price_precision)}</td>
            <td class="num mono ${dirClass(p.change)}">${fmtPct(p.changePct)}</td>
            <td class="num mono small">${fmtPrice(p.bid, ins.price_precision)} / ${fmtPrice(p.ask, ins.price_precision)}</td>
            <td>
              <button type="button" class="btn small" data-watch-id="${esc(ins.id)}" aria-pressed="${w}">
                ${w ? '★ Watching' : '☆ Watch'}
              </button>
            </td>
          </tr>`;
      }).join('');
    }
    status.textContent = `${filtered.length} of ${INSTRUMENTS.length} instruments${state.watchOnly ? ' (watchlist only)' : ''}.`;
  };

  rerender(latestSnapshot());
  unsub = subscribePrices((snap) => rerender(snap));

  onInput = () => { state.term = q.value; rerender(latestSnapshot()); };
  q.addEventListener('input', onInput);

  onClick = (e) => {
    const catBtn = e.target.closest('[data-cat]');
    if (catBtn) {
      state.cat = catBtn.dataset.cat;
      state.watchOnly = false;
      el.querySelectorAll('[data-cat],[data-watch]').forEach((b) => b.setAttribute('aria-pressed', String(b === catBtn)));
      rerender(latestSnapshot());
      return;
    }
    const watchBtn = e.target.closest('[data-watch]');
    if (watchBtn) {
      state.watchOnly = !state.watchOnly;
      watchBtn.setAttribute('aria-pressed', String(state.watchOnly));
      el.querySelectorAll('[data-cat]').forEach((b) => b.setAttribute('aria-pressed', 'false'));
      rerender(latestSnapshot());
      return;
    }
    const rowWatch = e.target.closest('[data-watch-id]');
    if (rowWatch) {
      const id = rowWatch.dataset.watchId;
      const next = toggleWatched(id);
      rowWatch.setAttribute('aria-pressed', String(next.includes(id)));
      rowWatch.textContent = next.includes(id) ? '★ Watching' : '☆ Watch';
      rerender(latestSnapshot());
    }
  };
  el.addEventListener('click', onClick);
}

export function unmount() {
  if (root && onClick) root.removeEventListener('click', onClick);
  if (unsub) unsub();
  stopPrices();
  root = unsub = onClick = onInput = null;
}
